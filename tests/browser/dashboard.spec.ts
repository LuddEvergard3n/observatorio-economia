test('mobile pages fit the viewport and dark theme persists', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.kpi-card').first()).toBeVisible()
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await expect(page.locator('.sidebar')).toBeHidden()
  await page.reload()
  await expect(page.locator('html')).toHaveClass(/dark/)
  for (const route of ['overview', 'compare', 'governments', 'trade', 'quality', 'idmi', 'sources', 'history', 'taxes', 'labor']) {
    await page.goto('/#' + route)
    await expect(page.locator('h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), route).toBe(true)
  }
  await page.goto('/#overview')
  await page.screenshot({ path: '.cache/mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Abrir menu' }).click()
  await expect(page.getByRole('complementary', { name: 'Navegação principal' }).getByRole('link', { name: 'Comparar países', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Abrir menu' })).toHaveAttribute('aria-expanded', 'false')
})

test('accessibility preferences are keyboard accessible and persist locally', async ({ page }) => {
  await page.goto('/')
  const open = page.getByRole('button', { name: 'Abrir opções de acessibilidade' })
  await open.focus()
  await page.keyboard.press('Enter')
  const panel = page.getByRole('region', { name: 'Acessibilidade' })
  await expect(panel).toBeVisible()
  await panel.getByRole('switch', { name: /Texto maior/ }).focus()
  await page.keyboard.press('Space')
  await panel.getByRole('switch', { name: /Alto contraste/ }).click()
  await panel.getByRole('switch', { name: /Reduzir movimento/ }).click()
  await page.screenshot({ path: '.cache/accessibility.png', fullPage: true })
  await expect(page.locator('html')).toHaveClass(/a11y-large-text/)
  await expect(page.locator('html')).toHaveClass(/a11y-high-contrast/)
  await expect(page.locator('html')).toHaveClass(/a11y-reduce-motion/)
  await page.reload()
  await expect(page.locator('html')).toHaveClass(/a11y-large-text/)
  await expect(page.locator('html')).toHaveClass(/a11y-high-contrast/)
  await expect(page.locator('html')).toHaveClass(/a11y-reduce-motion/)
  await page.getByRole('button', { name: 'Abrir opções de acessibilidade' }).click()
  await page.getByRole('button', { name: 'Restaurar padrão' }).click()
  await expect(page.locator('html')).not.toHaveClass(/a11y-/)
})

