import { test, expect } from '@playwright/test'

test('loads real snapshots, charts, methodology and CSV without provider requests', async ({ page }) => {
  const errors: string[] = [], external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:5173')) external.push(request.url()) })
  await page.goto('/')
  await expect(page.locator('.kpi-card').first()).toBeVisible()
  await expect(page.locator('canvas').first()).toBeVisible()
  await page.screenshot({ path: '.cache/desktop.png', fullPage: true })
  await page.goto('/#indicator/ipca?from=2020&to=2026')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('IPCA')
  await expect(page.locator('.chart-reading')).toContainText('Leitura rápida')
  await expect(page.locator('.chart-reading')).toContainText('Brasil')
  await expect(page.locator('.chart-context')).toContainText('Eventos documentados no período')
  await expect(page.locator('.chart-context').getByRole('link', { name: /IPCA · atualização dos pesos/ })).toHaveAttribute('href', '#history?event=ipca2020')
  await page.getByRole('tab', { name: 'Dados da série' }).click()
  await expect(page.locator('tbody tr').first()).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'CSV', exact: true }).click()
  expect((await downloaded).suggestedFilename()).toContain('ipca')
  await page.goto('/#indicator/hdi?from=2008&to=2026')
  await expect(page.getByText('Governo em exercício: Lula II · 2007–2010')).toBeVisible()
  await expect(page.getByText('Responsável pela metodologia: PNUD', { exact: false }).first()).toBeVisible()
  await expect(page.getByText('Edição 2023/24: Brasil em 2022 = 0,760', { exact: false })).toBeVisible()
  await page.goto('/#indicator/federal-debt?from=2017&to=2026')
  await expect(page.getByText('ago. de 2026', { exact: true }).first()).toBeVisible()
  await page.goto('/#idmi')
  await expect(page.getByText('Nota geral não publicada', { exact: true })).toBeVisible()
  await expect(page.getByText('IDMI9 2023 · experimental', { exact: true })).toBeVisible()
  await page.goto('/#history')
  await expect(page.getByText('EC 40', { exact: false }).first()).toBeVisible()
  expect(errors).toEqual([])
  expect(external).toEqual([])
})

test('mobile pages fit the viewport and dark theme persists', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.kpi-card').first()).toBeVisible()
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await expect(page.locator('.sidebar')).toBeHidden()
  await page.reload()
  await expect(page.locator('html')).toHaveClass(/dark/)
  for (const route of ['overview', 'compare', 'idmi', 'sources', 'history', 'labor']) {
    await page.goto('/#' + route)
    await expect(page.locator('h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), route).toBe(true)
  }
  await page.goto('/#overview')
  await page.screenshot({ path: '.cache/mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Abrir menu' }).click()
  await expect(page.getByRole('complementary', { name: 'Navegação principal' }).getByRole('link', { name: 'Comparar países', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Abrir menu' })).toHaveAttribute('aria-expanded', 'false')
})

test('language selector persists a supported interface locale without provider requests', async ({ page }) => {
  await page.goto('/')
  const selector = page.locator('.language-select select')
  await expect(selector.locator('option')).toHaveCount(10)
  await selector.selectOption('en')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.locator('.sidebar').getByRole('link', { name: 'Compare countries', exact: true })).toBeVisible()
  await selector.selectOption('ru')
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru')
  await expect(page.locator('.sidebar').getByRole('link', { name: 'Сравнить страны', exact: true })).toBeVisible()
})
